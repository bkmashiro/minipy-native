#!/usr/bin/env python3
"""Bounded Apple-clang stencil extraction, no downloads or handwritten opcodes."""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'evidence/cb-copy-patch'
SCRATCH = Path.home() / '.hermes/cache/scratch'
COMMAND = ['xcrun', 'clang', '-target', 'arm64-apple-macos14', '-O2',
           '-fno-stack-protector', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables',
           '-fno-vectorize', '-fno-slp-vectorize', '-c', str(OUT / 'stencils.c')]

def sha(data):
    return hashlib.sha256(data).hexdigest()

def extract(data):
    # Deliberately accepts only this little-endian ARM64 Mach-O object format.
    magic, cpu, sub, kind, count, size, flags, reserved = struct.unpack_from('<8I', data)
    if (magic, cpu, kind) != (0xfeedfacf, 0x100000c, 1):
        raise ValueError('not an ARM64 Mach-O object')
    pos = 32
    section = None
    symbols = None
    for _ in range(count):
        cmd, length = struct.unpack_from('<II', data, pos)
        if cmd == 0x19:  # LC_SEGMENT_64
            nsects = struct.unpack_from('<I', data, pos + 64)[0]
            for i in range(nsects):
                at = pos + 72 + i * 80
                name, segment, addr, nbytes, offset, align, relocoff, nreloc, *_ = struct.unpack_from('<16s16sQQ8I', data, at)
                name = name.rstrip(b'\0')
                if name != b'__text' and nbytes:
                    raise ValueError(f'unexpected nonempty section {name!r}')
                if name == b'__text':
                    section = (addr, data[offset:offset+nbytes], relocoff, nreloc)
        elif cmd == 2:  # LC_SYMTAB
            symbols = struct.unpack_from('<4I', data, pos + 8)
        pos += length
    if pos != 32 + size or not section or not symbols:
        raise ValueError('unexpected load commands')
    symoff, nsyms, stroff, strsize = symbols
    names, defined = [], {}
    strings = data[stroff:stroff+strsize]
    for i in range(nsyms):
        nameoff, typ, sect, desc, value = struct.unpack_from('<IBBHQ', data, symoff + i * 16)
        name = strings[nameoff:].split(b'\0', 1)[0].decode()
        names.append(name)
        if typ == 0xf and sect == 1:
            defined[name] = value
    if set(defined) != {'_add', '_sub', '_mul', '_done'}:
        raise ValueError(f'unexpected symbols {defined}')
    addr, code, reloff, nrel = section
    relocations = []
    for i in range(nrel):
        at, bits = struct.unpack_from('<II', data, reloff + i * 8)
        sym = bits & 0xffffff
        if bits >> 24 != 0x2d or names[sym] != '_next':
            raise ValueError('only ARM64_RELOC_BRANCH26 pcrel external length=2 allowed')
        relocations.append(at)
    result = {}
    ordered = sorted(defined.items(), key=lambda kv: kv[1])
    for i, (name, start) in enumerate(ordered):
        end = ordered[i+1][1] if i+1 < len(ordered) else addr + len(code)
        blob = code[start-addr:end-addr]
        holes = [at-(start-addr) for at in relocations if start-addr <= at < end-addr]
        if (name == '_done' and holes) or (name != '_done' and len(holes) != 1):
            raise ValueError('unexpected continuation relocations')
        for hole in holes:
            if hole % 4 or struct.unpack_from('<I', blob, hole)[0] != 0x14000000:
                raise ValueError('continuation must be unconditional B with zero addend')
        result[name[1:]] = {'bytes': list(blob), 'next': holes[0] if holes else None,
                           'offset': start, 'sha256': sha(blob)}
    return result

def main():
    SCRATCH.mkdir(parents=True, exist_ok=True)
    obj = SCRATCH / 'cb-stencils.o'
    with (SCRATCH / 'minipy-perf-build.lock').open('a+') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        cmd = COMMAND + ['-o', str(obj)]
        subprocess.run(cmd, check=True, cwd=ROOT)
        data = obj.read_bytes()
        templates = extract(data)
        metadata = {'command': cmd, 'compiler': subprocess.check_output(['xcrun', 'clang', '--version'], text=True),
                    'source_sha256': sha((OUT / 'stencils.c').read_bytes()), 'object_sha256': sha(data),
                    'object_bytes': len(data), 'template_bytes': sum(len(t['bytes']) for t in templates.values()),
                    'templates': templates,
                    'disassembly': subprocess.check_output(['xcrun', 'llvm-objdump', '--macho', '--disassemble', '--reloc', '--syms', '--section-headers', str(obj)], text=True)}
        (OUT / 'templates.json').write_text(json.dumps(metadata, indent=2) + '\n')
        rust = '// Generated by tools/cb_templates.py from Apple clang output; do not hand-edit.\n'
        for name, item in templates.items():
            rust += f'pub const {name.upper()}: &[u8] = &{item["bytes"]!r};\n'
            if item['next'] is not None:
                rust += f'pub const {name.upper()}_NEXT: usize = {item["next"]};\n'
        (OUT / 'templates.rs').write_text(rust)
        subprocess.run(['rustfmt', '--edition', '2024', str(OUT / 'templates.rs')], check=True)
        obj.unlink()
    print(json.dumps({'template_bytes': metadata['template_bytes'], 'object_bytes': len(data), 'source_sha256': metadata['source_sha256']}))

if __name__ == '__main__':
    main()
